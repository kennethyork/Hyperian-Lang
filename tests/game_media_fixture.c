static int write_file(const char *path, const unsigned char *data, size_t size) {
    FILE *file = fopen(path, "wb");
    if (!file) return 0;
    int okay = fwrite(data, 1, size, file) == size;
    if (fclose(file)) okay = 0;
    return okay;
}

